def encode_features(df: pd.DataFrame) -> pd.DataFrame:
    """Stage 2: convert Stage 1 MultiIndex DataFrame into encoded flat DataFrame.

    Parameters
    ----------
    df : pd.DataFrame
        Stage 1 output with 3-level MultiIndex (descriptive, original, subset).

    Returns
    -------
    pd.DataFrame
        Flat DataFrame with encoded, imputed features ready for factor analysis.
        Contains the factor analysis feature columns plus 'ahi' as target.
    """
    df = df.copy()

    # Step 1: Flatten MultiIndex → flat column names
    df = _flatten_multiindex(df)

    # Step 2: Compute work schedule time diffs
    df = _compute_work_schedule_diffs(df)

    # Step 3: Recompute map_likelihood_ration from map_score (raw data is broken)
    df = _recompute_map_lr(df)

    # Step 4: One-hot encode RLS probability
    df = _one_hot_encode_rls(df)

    # Step 5: Merge compound columns
    df = _merge_exercise(df)
    df = _merge_caffeine(df)
    df = _merge_naps(df)
    df = _merge_nightmares(df)
    df = _merge_sleepiness_columns(df)
    df = _merge_dreams(df)

    # Step 5: Select factor analysis columns
    available = [c for c in _FACTOR_COLUMNS if c in df.columns]
    missing = [c for c in _FACTOR_COLUMNS if c not in df.columns]
    if missing:
        import warnings

        warnings.warn(f"Missing columns for factor analysis: {missing}")
    df = df[available]

    # Step 6: Encode categorical features
    df = _encode_sex(df)
    df = _encode_exercise(df)
    df = _encode_naps(df)
    df = _encode_daytime_sleepiness(df)
    df = _encode_dream_recall(df)

    # Step 7: Convert boolean columns to int
    df = _convert_booleans(df, ["never_smoked", "never_feel_rested"])
    df = _convert_booleans(df, _MDHX_BOOL_COLS)

    # Step 8: Drop rows missing AHI
    df = df.dropna(subset=["ahi"])

    # Step 9: Replace placeholder values
    df = _replace_placeholders(df)

    # Step 10: Impute
    df = _impute(df)

    # Step 11: One-hot encode dream_recall_frequency
    df = _one_hot_encode_dream_recall(df)

    return df



def _one_hot_encode_rls(df: pd.DataFrame) -> pd.DataFrame:
    """One-hot encode rls_probability into 4 boolean columns."""
    if "rls_probability" not in df.columns:
        return df

    dummies = pd.get_dummies(df["rls_probability"], prefix="rls")
    rename_map = {}
    for c in dummies.columns:
        val = c.replace("rls_", "")
        if val == "Likely":
            rename_map[c] = "rls_likely_curr"
        elif val == "Possible":
            rename_map[c] = "rls_possible_curr"
        elif val == "Unlikely":
            rename_map[c] = "rls_unlikely_curr"
        elif "possibly in past" in val.lower():
            rename_map[c] = "rls_unlikely_curr_probably_past"
    dummies = dummies.rename(columns=rename_map)
    df = pd.concat([df.drop(columns=["rls_probability"]), dummies], axis=1)
    return df



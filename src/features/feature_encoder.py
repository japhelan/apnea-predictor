def _encode_sex(df: pd.DataFrame) -> pd.DataFrame:
    df["sex"] = df["sex"].map({"M": 0, "F": 1})
    return df


def _encode_exercise(df: pd.DataFrame) -> pd.DataFrame:
    df["exercise_amt_or_time"] = df["exercise_amt_or_time"].map(
        {
            "rarely_or_never": 0,
            "between dinner and bedtime": 1,
            "late morning": 1,
            "early morning": 1,
            "early afternoon": 1,
            "late afternoon": 1,
        }
    )
    return df


def _encode_naps(df: pd.DataFrame) -> pd.DataFrame:
    """Encode nap_num string → binary frequent_naps (1 if per week, else 0)."""
    df["nap_num"] = np.where(
        df["nap_num"].astype(str).str.contains("per week", na=False),
        1,
        0,
    )
    df = df.rename(columns={"nap_num": "frequent_naps"})
    return df


def _encode_daytime_sleepiness(df: pd.DataFrame) -> pd.DataFrame:
    col = "difficulty_staying_awake_during_the_day_number_of_times"
    if col not in df.columns:
        return df
    df[col] = np.where(
        df[col].astype(str).str.contains("Day", na=False),
        1,
        np.where(
            df[col].astype(str).str.contains("Week", na=False),
            1,
            0,
        ),
    )
    df = df.rename(columns={col: "frequent_daytime_sleepiness"})
    return df


def _encode_dream_recall(df: pd.DataFrame) -> pd.DataFrame:
    """Encode remember_dreams_times → dream_recall_frequency (frequent/infrequent/rarely_or_never)."""
    col = "remember_dreams_times"
    if col not in df.columns:
        return df

    dream_count = df[col].str.extract(r"(\d+)").astype(float)
    dream_tf = df[col].str.extract(r"per\s(\w+)").iloc[:, 0]

    df[col] = np.where(
        (dream_count[0] >= 3)
        & ((dream_tf == "week") | ((dream_tf == "month") & (dream_count[0] >= 12))),
        "frequent",
        np.where(
            (dream_count[0] < 3)
            & ((dream_tf == "week") | ((dream_tf == "month") & (dream_count[0] < 12))),
            "infrequent",
            "rarely_or_never",
        ),
    )
    df = df.rename(columns={col: "dream_recall_frequency"})
    return df


def _convert_booleans(df: pd.DataFrame, columns: list[str]) -> pd.DataFrame:
    """Convert boolean columns to int (fillna False first)."""
    for col in columns:
        if col in df.columns:
            df[col] = df[col].fillna(0).astype(int)
    return df


def _replace_placeholders(df: pd.DataFrame) -> pd.DataFrame:
    """Replace -66 and -55 placeholder values with NA across all columns."""
    df = df.replace([-55, -66, -44], pd.NA)
    return df


def _impute(df: pd.DataFrame) -> pd.DataFrame:
    """Impute numeric columns with median, categorical with mode."""
    from sklearn.impute import SimpleImputer

    num_cols = df.select_dtypes(include=["int64", "float64", "Int32"]).columns
    cat_cols = df.select_dtypes(include=["object", "bool"]).columns

    if len(num_cols) > 0:
        median_imputer = SimpleImputer(strategy="median")
        df[num_cols] = median_imputer.fit_transform(df[num_cols])

    if len(cat_cols) > 0:
        mode_vals = df[cat_cols].mode().iloc[0]
        with pd.option_context("future.no_silent_downcasting", True):
            for col in cat_cols:
                df[col] = df[col].fillna(mode_vals[col]).infer_objects(copy=False)

    return df


def _one_hot_encode_dream_recall(df: pd.DataFrame) -> pd.DataFrame:
    """One-hot encode dream_recall_frequency, dropping first category."""
    from sklearn.preprocessing import OneHotEncoder

    col = "dream_recall_frequency"
    if col not in df.columns:
        return df

    ohe = OneHotEncoder(sparse_output=False, drop="first")
    encoded = ohe.fit_transform(df[[col]])
    cat_names = ohe.get_feature_names_out([col])
    encoded_df = pd.DataFrame(encoded, columns=cat_names, index=df.index)
    df = pd.concat([df.drop(columns=[col]), encoded_df], axis=1)
    return df


